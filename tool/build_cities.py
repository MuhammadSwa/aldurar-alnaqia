# --- Download helpers ------------------------------------------------------


def download(url: str, dest: Path, force: bool = False) -> Path:
    if dest.exists() and not force:
        print(f"  reuse {dest.name}")
        return dest
    print(f"  downloading {url} ...")
    dest.parent.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(url, timeout=120) as resp, open(dest, "wb") as fh:
        fh.write(resp.read())
    return dest


# --- Main ------------------------------------------------------------------


def build(work_dir: Path, force: bool = False) -> dict:
    cities_zip = download(CITIES_URL, work_dir / "cities15000.zip", force)
    ar_path = download(COUNTRIES_AR_URL, work_dir / "countries_ar.json", force)
    en_path = download(COUNTRIES_EN_URL, work_dir / "countries_en.json", force)

    with open(ar_path, encoding="utf-8") as fh:
        countries_ar: dict[str, str] = json.load(fh)
    with open(en_path, encoding="utf-8") as fh:
        countries_en: dict[str, str] = json.load(fh)

    with zipfile.ZipFile(cities_zip) as zf:
        names = [n for n in zf.namelist() if n.endswith(".txt")]
        raw = zf.read(names[0]).decode("utf-8")

    entries: list[tuple[int, dict]] = []
    missing_ar = 0
    for line in raw.splitlines():
        if not line.strip():
            continue
        f = line.split("\t")
        # GeoNames dump columns: 0 id, 1 name, 2 asciiname, 3 alternates,
        # 4 lat, 5 lng, 8 country code, 14 population.
        asciiname = f[2] or f[1]
        country = f[8]
        try:
            population = int(f[14] or 0)
        except ValueError:
            population = 0
        ar = best_arabic_name(f[3])
        if ar is None:
            ar = AR_OVERRIDES.get((asciiname, country))
        if ar is None:
            missing_ar += 1
        city: dict = {
            "en": asciiname,
            "country": country,
            "lat": round(float(f[4]), 3),
            "lng": round(float(f[5]), 3),
        }
        if ar is not None:
            city["ar"] = ar
        entries.append((population, city))

    entries.sort(key=lambda e: -e[0])
    cities = [c for _, c in entries]

    used_countries = sorted({c["country"] for c in cities})
    countries = {
        code: {
            "ar": countries_ar.get(code),
            "en": countries_en.get(code, code),
        }
        for code in used_countries
    }
    # Drop null Arabic country names (app falls back to English).
    for info in countries.values():
        if info["ar"] is None:
            del info["ar"]

    # --- Regional overrides ------------------------------------------------
    # Jerusalem (GeoNames lists it under IL) belongs to Palestine in this
    # app; all other IL entries are dropped.
    for c in cities:
        if c.get("country") == "IL" and c.get("en") == "Jerusalem":
            c["country"] = "PS"
            c["ar"] = "القدس الشريف"
    cities = [
        c for c in cities
        if c.get("country") != "IL"
    ]
    countries.pop("IL", None)
    if "PS" in countries:
        countries["PS"] = {"ar": "فلسطين", "en": "Palestine"}

    with_ar = sum(1 for c in cities if "ar" in c)
    print(f"  cities: {len(cities)} ({with_ar} with Arabic name)")
    print(f"  cities without Arabic (English fallback): {missing_ar}")
    print(f"  countries: {len(countries)}")
    return {"version": 1, "attribution": ATTRIBUTION,
            "countries": countries, "cities": cities}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--work-dir", type=Path,
                        default=Path("/tmp/opencode/citydata"))
    parser.add_argument("--force", action="store_true",
                        help="re-download cached source files")
    args = parser.parse_args()

    print("Building offline city database ...")
    data = build(args.work_dir, args.force)
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, separators=(",", ":"))
    size_mb = OUT_PATH.stat().st_size / 1e6
    print(f"  wrote {OUT_PATH} ({size_mb:.2f} MB)")


if __name__ == "__main__":
    main()
