#!/usr/bin/env python3
"""Build the offline city database for the prayer-timings city picker.

Reads the GeoNames ``cities15000`` dump (all populated places with
population > 15000, ~34k entries) and produces a compact JSON asset with
**Arabic + English names only**:

    assets/data/cities.json

Schema::

    {
      "version": 1,
      "attribution": "...",
      "countries": {"EG": {"ar": "مصر", "en": "Egypt"}, ...},
      "cities": [
        {"en": "Cairo", "ar": "القاهرة", "country": "EG",
         "lat": 30.063, "lng": 31.250},
        ...
      ]
    }

* ``cities`` is sorted by population (descending) so the app can use the
  position as a popularity signal for search ranking.
* ``ar`` is omitted when no clean Arabic name exists; the app then shows
  and searches the English name.
* Coordinates are rounded to 3 decimals (~110 m, far more precise than
  prayer-time math needs) to keep the asset small.

Arabic-name extraction: GeoNames ``alternatenames`` mixes Arabic with
Urdu / Persian / Uyghur spellings written in Arabic script.  Candidates
are restricted to core Arabic letters (U+0621-U+064A, i.e. no Persian
gaf/kaf/yeh etc.), diacritics are stripped, then scored: bonus for the
``ال`` prefix and proper orthography (``أإآؤئة``), penalty for
administrative qualifiers (``إمارة``/``ولاية``/...) and long
descriptions.  Egyptian towns missing from GeoNames Arabic alternates
get curated overrides in ``AR_OVERRIDES``.

Usage::

    python3 tool/build_cities.py [--work-dir /tmp/citydata] [--force]

The script downloads (once, cached in ``work-dir``):
  * https://download.geonames.org/export/dump/cities15000.zip  (CC BY 4.0)
  * https://raw.githubusercontent.com/umpirsky/country-list/master/data/ar/country.json  (MIT)
  * https://raw.githubusercontent.com/umpirsky/country-list/master/data/en/country.json  (MIT)
"""

from __future__ import annotations

import argparse
import json
import re
import urllib.request
import zipfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_PATH = REPO_ROOT / "assets" / "data" / "cities.json"

CITIES_URL = "https://download.geonames.org/export/dump/cities15000.zip"
COUNTRIES_AR_URL = (
    "https://raw.githubusercontent.com/umpirsky/country-list/master"
    "/data/ar/country.json"
)
COUNTRIES_EN_URL = (
    "https://raw.githubusercontent.com/umpirsky/country-list/master"
    "/data/en/country.json"
)

ATTRIBUTION = (
    "City coordinates (c) GeoNames (CC BY 4.0, geonames.org), "
    "cities15000 dump. Arabic/English country names (c) "
    "umpirsky/country-list (MIT). Generated by tool/build_cities.py."
)

# --- Arabic extraction -----------------------------------------------------

# Core Arabic letters only: U+0621-U+064A + space.  Excludes Persian/Urdu
# extensions (گ چ پ ژ ے ھ ە ...) so Urdu/Persian/Uyghur variants drop out.
CORE_ARABIC = re.compile(r"^[\u0621-\u064A ]+$")
ARABIC_SCRIPT = re.compile(r"[\u0600-\u06FF]")
# Diacritics and tatweel: removed. Zero-width joiners: turned into spaces
# (they join compound names, e.g. 'باب\u200cالزوار' -> 'باب الزوار').
REMOVE_CHARS = re.compile(r"[\u064B-\u0652\u0670\u0640]")
SPACE_CHARS = re.compile(r"[\u200C\u200D]")
MULTISPACE = re.compile(r"\s+")

# Administrative/descriptive qualifiers: picking the bare city name reads
# better in a picker ("الشارقة" not "إمارة الشارقة").
QUALIFIERS = {
    "إمارة",
    "امارة",
    "ولاية",
    "محافظة",
    "مقاطعة",
    "استان",
    "جزيرة",
    "بلدية",
    "إقليم",
    "اقليم",
    "مدينة",
}
# Bonus for proper MSA orthography: hamza forms, ta-marbuta and ya
# (dialectal variants tend to write ا/ه/ى instead).
PROPER_BONUS_CHARS = "أإآؤئةي"


def clean_candidate(raw: str) -> str:
    """Strip diacritics/tatweel and collapse whitespace."""
    no_marks = REMOVE_CHARS.sub("", raw)
    spaced = SPACE_CHARS.sub(" ", no_marks)
    return MULTISPACE.sub(" ", spaced).strip()


def score_candidate(name: str) -> int:
    words = name.split(" ")
    score = len(name)
    if name.startswith("ال"):
        score += 3
    score += sum(name.count(ch) for ch in PROPER_BONUS_CHARS)
    score -= 10 * sum(1 for w in words if w in QUALIFIERS)
    if len(words) > 2:
        score -= 3 * (len(words) - 2)
    return score


def best_arabic_name(alternates_raw: str) -> str | None:
    """Pick one clean Modern Standard Arabic name, or None."""
    seen: set[str] = set()
    candidates: list[str] = []
    for raw in alternates_raw.split(","):
        if not ARABIC_SCRIPT.search(raw):
            continue
        name = clean_candidate(raw)
        if len(name) < 2 or name in seen:
            continue
        seen.add(name)
        if CORE_ARABIC.match(name):
            candidates.append(name)
    if not candidates:
        return None
    # Prefer concise names: drop long descriptions when a short name exists
    # (e.g. keep 'أبوظبي', not 'جزيرة أبوظبي وجزر داخلية اخرى').
    short = [n for n in candidates if len(n.split(" ")) <= 3]
    if short:
        candidates = short
    candidates.sort(key=lambda n: (-score_candidate(n), len(n.split(" ")), len(n)))
    return candidates[0]


